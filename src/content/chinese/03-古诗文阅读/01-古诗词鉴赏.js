        "**词牌名**：词牌是词的格式的名称，规定词的句数、字数、平仄和用韵，如《水调歌头》《念奴娇》《菩萨蛮》《浣溪沙》等。词牌与词的内容并无必然联系，有的词人会在词牌下另加题目或小序，点明写作内容或缘由，如苏轼《水调歌头·明月几时有》。",
